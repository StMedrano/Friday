import {test,expect} from '@playwright/test'
test('create and reload a persisted fixture task; denied/failed writes never appear saved',async({page})=>{
 await page.goto('/')
 await page.getByRole('button',{name:'Tasks',exact:true}).click()
 await page.getByLabel('Project',{exact:true}).selectOption('project-a')
 await page.getByLabel('Task title').fill('Browser persisted fixture')
 await page.getByLabel('Objective',{exact:true}).fill('Verify isolated fixture persistence')
 await page.getByRole('button',{name:'Create task',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Browser persisted fixture'})).toBeVisible()
 await page.reload()
 await page.getByRole('button',{name:'Tasks',exact:true}).click()
 await page.getByLabel('Project',{exact:true}).selectOption('project-a')
 await expect(page.getByRole('heading',{name:'Browser persisted fixture'})).toBeVisible()
 await page.getByLabel('Task title').fill('Fail fixture write')
 await page.getByLabel('Objective',{exact:true}).fill('A deliberate fixture failure')
 await page.getByRole('button',{name:'Create task',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('Task storage unavailable')
 await expect(page.getByLabel('Task title')).toHaveValue('Fail fixture write')
 await expect(page.getByRole('heading',{name:'Fail fixture write'})).toHaveCount(0)
 const denied=await page.request.post('/api/projects/private/tasks',{data:{title:'Denied'},headers:{origin:'http://127.0.0.1:8772'}})
 expect(denied.status()).toBe(403)
})
test('phone task form stays within viewport and access denial clears private content',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/')
 await page.getByRole('button',{name:'More',exact:true}).click();await page.getByRole('button',{name:'Tasks',exact:true}).click()
 await page.getByLabel('Project',{exact:true}).selectOption('project-a')
 await expect(page.getByLabel('Task title')).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
 await page.route('**/api/projects',route=>route.fulfill({status:403,contentType:'application/json',body:'{"error":"not-authorized"}'}))
 await page.reload();await page.getByRole('button',{name:'More',exact:true}).click();await page.getByRole('button',{name:'Tasks',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('Project access denied')
 await expect(page.getByLabel('Task title')).toHaveCount(0)
})
